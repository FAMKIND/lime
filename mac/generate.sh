#!/bin/sh
# Regenerates mac/LimeMac.xcodeproj from project.yml (the .xcodeproj is gitignored), after writing the backend config
# (as ios/generate.sh does: from supabase/.staging.public.env, public values only) and building LimeCore for the Mac.
set -e
cd "$(dirname "$0")"
command -v xcodegen >/dev/null 2>&1 || { echo "XcodeGen is missing: brew install xcodegen" >&2; exit 1; }

BACKEND_FILE="Lime/Generated/BackendConfig.generated.swift"
PUBLIC_ENV="../supabase/.staging.public.env"
URL=""
KEY=""
if [ -f "$PUBLIC_ENV" ]; then
  URL="$(sed -n 's/^SUPABASE_URL=//p' "$PUBLIC_ENV" | head -1)"
  KEY="$(sed -n 's/^SUPABASE_ANON_KEY=//p' "$PUBLIC_ENV" | head -1)"
fi

# LimeCore (Rust) for the Mac: skipped when the xcframework is newer than every core source.
XCF="Frameworks/LimeCoreFFI.xcframework"
if [ ! -d "$XCF" ] || [ -n "$(find ../core/src ../core/Cargo.toml ../core/Cargo.lock build-core.sh -newer "$XCF" 2>/dev/null | head -1)" ]; then
  ./build-core.sh
fi

mkdir -p "$(dirname "$BACKEND_FILE")"
{
  echo "// Generated by mac/generate.sh from supabase/.staging.public.env. Do not edit or commit."
  echo "enum GeneratedBackend {"
  if [ -n "$URL" ] && [ -n "$KEY" ]; then
    echo "    static let url: String? = \"$URL\""
    echo "    static let apiKey: String? = \"$KEY\""
  else
    echo "    static let url: String? = nil"
    echo "    static let apiKey: String? = nil"
  fi
  echo "    static let donateURL: String? = nil"
  echo "}"
} > "$BACKEND_FILE"

# Generate-time patches (not hand copies): two Catalyst-unavailable API uses in ios/ files, until plot-iOS adds guards
# (see TEND-MAC.md "Stand-ins"). Each patched copy is written into the gitignored Lime/Generated/ and the original is
# excluded from the Mac target in project.yml. Fails loudly if the line to patch has moved.
python3 -I - <<'PY'
import sys
patches = [
    ("../ios/Lime/Core/Calls/GroupCallManager.swift", "Lime/Generated/GroupCallManager.swift",
     [("        let session = AVCaptureSession()\n        let device = UIDevice", "        let device = UIDevice"), ("session.isMultitaskingCameraAccessSupported", "false"), ("session.isMultitaskingCameraAccessEnabled", "false")]),
    ("../ios/Lime/Features/Chat/Composer/ComposerDocument.swift", "Lime/Generated/ComposerDocument.swift",
     [("return UIFont(descriptor: slanted.fontDescriptor.withMatrix(slant), size: base.pointSize)", "_ = slant; return slanted")]),
]
for src, dst, edits in patches:
    text = open(src).read()
    for old, new in edits:
        if text.count(old) != 1:
            sys.exit(f"generate.sh: the line to patch is not in {src} exactly once any more: {old!r}. Update the patch (and tell plot-iOS).")
        text = text.replace(old, new)
    open(dst, "w").write("// Generated by mac/generate.sh: a patched copy of " + src + ". Do not edit or commit.\n" + text)
PY

xcodegen generate --spec project.yml
